package com.yayuy.overgrownvegetation.base.plan;

/**
 * 基地に置く建物・設備の種類と、正面(入口)を南へ向けたときの大きさ(幅 = x、奥行 = z)。2026-10-01、大きさは仮決め。
 *
 * <p>ユーザー指定の建物は 管理棟・兵舎・弾薬庫・工廠・見張り台・倉庫(+門・壁)。そのほかは米軍の前線基地(FOB)を
 * 手本にした小物(シェルター・発電機・給水塔・仮設トイレ・コンテナ置き場・車両の屋根・ヘリパッド・旗竿)。
 * 兵舎はテント(ユーザー指定 2026-10-01「居住区は家というよりテントみたいな感じ」。米軍の TEMPER テントの写し)、
 * 倉庫は後のレベルの区画ほど本格的な建物になる(天幕 → 鉄骨)—— 前線の基地が仮設 → 半恒久 → 恒久と育つ流れの写し。
 */
public enum BuildingKind {
    /** 管理棟(司令部)。階数は基地レベルで増える。中に管理端末。 */
    HQ("管理棟", 15, 11),
    /** 兵舎: 砂色のかまぼこ形のテント(レベル 1〜3 の区画)。入口は妻側。 */
    BARRACKS_TENT("兵舎(テント)", 7, 11),
    /** 兵舎: 長い大型テント(レベル 4〜5 の区画)。棟は正面と平行、真ん中に前室の入口、前に空調機。 */
    BARRACKS_TENT_LARGE("兵舎(大型テント)", 15, 11),
    /** 倉庫: 天幕(テンション膜構造。レベル 1〜2 の区画)。 */
    WAREHOUSE_TENT("倉庫(天幕)", 11, 11),
    /** 倉庫: 鉄骨(レベル 3〜 の区画)。 */
    WAREHOUSE("倉庫", 17, 11),
    /** コンテナ置き場(大きさは区画に合わせて決める)。 */
    CONTAINER_YARD("コンテナ置き場", 0, 0),
    /** 弾薬庫: 土を被せたかまぼこ形の掩体 + 土嚢の土手。 */
    AMMO_BUNKER("弾薬庫", 9, 11),
    /** 工廠: 大扉の整備工場。 */
    WORKSHOP("工廠", 15, 11),
    /** 車両の屋根(柱と屋根だけ)。 */
    VEHICLE_SHED("車両の屋根", 13, 7),
    /** 駐車場(大きさは区画に合わせる)。 */
    PARKING("駐車場", 0, 0),
    /** 見張り台。外周の角と辺に載る。中は階段(エレベーターは作らない、ユーザー指定)。レベル 1〜3 は木造、4〜5 は鉄筋。 */
    WATCHTOWER("見張り台", 5, 5),
    /** 正門(7 マスの門 + 両脇。レベル 1〜3 は土嚢の詰所、4〜5 は鉄筋の塔)。 */
    GATEHOUSE("正門", 17, 5),
    /** 正門の外の検問所(ジグザグの車止め・詰所・投光器)。正面は外向き。 */
    CHECKPOINT("検問所", 15, 11),
    /** ヘリパッド。 */
    HELIPAD("ヘリパッド", 11, 11),
    /** 旗竿。 */
    FLAGPOLE("旗竿", 3, 3),
    /** 退避壕(迫撃砲よけのシェルター)。 */
    SHELTER("退避壕", 5, 3),
    /** 発電機。 */
    GENERATOR("発電機", 5, 3),
    /** 給水塔。 */
    WATER_TANK("給水塔", 5, 5),
    /** 仮設トイレの列。 */
    LATRINE("仮設トイレ", 5, 2),
    /** コンテナ 1 つ(長い辺を道へ向ける。ときどき 2 段)。区画どうしの間を埋める小物。 */
    CONTAINER("コンテナ", 7, 3),
    /** 照明塔(移動式の投光器: 黄色の台車に柱と投光器)。 */
    LIGHT_TOWER("照明塔", 3, 3),
    /** 防爆壁(コンクリートの低い防護壁の並び)。 */
    BARRIER("防爆壁", 6, 1),
    /** 中継の除去塔: 浄化圏の真ん中の広場に立つ柱と見張り床、天辺に胞子除去装置(ユーザー指定 2026-10-02「案 E」)。 */
    PURIFIER_MAST("除去塔", 5, 5),
    /** 大除去塔: 中心の浄化圏の管理棟の裏に立つ、いちばん高い塔(基地の目印)。 */
    PURIFIER_TOWER("大除去塔", 7, 7),
    // ---- 2026-10-02 夜: 種類ごとの特別な施設(ユーザー指定)。後ろに足す(番号は区画の種に入るので、前の建物の番号を変えない) ----
    /** 医療テント(野戦病院): 白い羊毛のかまぼこ形、正面の入口の上に小さな赤十字、中は簡易ベッドの列と処置台。 */
    MEDICAL_TENT("医療テント", 11, 11),
    /**
     * 野外研究施設(研究基地の出城に 1 棟だけ): 腰を据えた大きな研究所(3 階建ての本館、2 階建ての研究棟、ガラスの温室の棟)。
     * ユーザー指定 2026-10-02 夜「即席のようなものではなくガッツリそこに構えて研究している感じ」「何棟も置かず、一棟だけ大きな施設」。
     */
    FIELD_LAB("野外研究施設", 25, 19),
    /** 観測施設(観測基地の出城): レドーム(白い球の覆い)を載せた観測塔と、計器の小屋・アンテナ。 */
    OBSERVATION_POST("観測施設", 11, 11),
    // ---- 2026-10-02 夜その 3: 研究所の増築(ユーザー指定「出城が拡張される際、研究施設も一緒に拡張される。縦に伸ばすのではなく、拡張された場所も使った巨大な施設群」)。後ろに足す ----
    /** 第 2 研究棟(研究の出城の増築): 2 階建ての研究棟。屋上に太陽光パネル。左右の壁の真ん中に連絡通路の出入口。 */
    ANNEX_LAB("第 2 研究棟", 27, 19),
    /** 大型試験棟(研究の出城の増築): 天井の高い試験場。正面に大扉、中に天井クレーンと試作の戦闘ロボット。左右に連絡通路の出入口。 */
    TEST_HALL("大型試験棟", 27, 19),
    /** 連絡通路: 研究所の棟どうしを結ぶ屋根付きの通路(幅 5、長さは区画で決める)。床は両端の棟の高さに合わせて段で上り下りする。 */
    RESEARCH_WALKWAY("連絡通路", 0, 0);

    public final String label;
    public final int width;
    public final int depth;

    BuildingKind(String label, int width, int depth) {
        this.label = label;
        this.width = width;
        this.depth = depth;
    }
}
