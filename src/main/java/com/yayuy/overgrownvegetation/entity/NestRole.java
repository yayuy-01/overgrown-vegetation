package com.yayuy.overgrownvegetation.entity;

/**
 * 過繫茂 Mob の<b>巣との関わり方</b>(2026-09-20)。個体ごとに 1 つ持ち、エンティティと一緒に保存される。
 *
 * <p>役割で変わるのは<b>誰を狙うか</b>と<b>どこへ歩くか</b>の 2 つだけ。攻撃力や見た目は変わらない。
 */
public enum NestRole {

    /** ふつうの個体。今までどおり群れを作り、狩りをする。 */
    NONE,

    /**
     * <b>巣の住人</b>(衛兵室の個体、卵から孵った個体)。
     * 巣から {@code guardLeashRadius} より外の相手は狙わない —— 外の敵に釣られて巣を空にしないため
     * (ユーザー指定 2026-09-20)。小規模レイドの増援に選ばれると {@link #NONE} に戻って外へ出る。
     */
    RESIDENT,

    /**
     * <b>建設グループ</b>の一員(ユーザー指定 2026-09-20)。アルボラだけで 15 体を組み、
     * 過繫茂バイオームから離れた場所まで歩いて巣を作る。
     *
     * <p>道中は<b>自分が攻撃されるまで何も攻撃しない</b>。巣を作り終えると解散して {@link #NONE} に戻る。
     */
    BUILDER
}
